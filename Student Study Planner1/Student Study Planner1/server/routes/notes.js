const express = require('express');
const router = express.Router();
const db = require('../config/db');
const { authenticateToken } = require('../middleware/authMiddleware');
const { generateStudyNotes } = require('../services/claudeService');

// Get all saved notes for user
router.get('/', authenticateToken, async (req, res) => {
  try {
    const studentId = req.query.student_id && req.user.role === 'parent' ? req.query.student_id : req.user.id;
    const { course_id } = req.query;

    let sql = `
      SELECT n.*, c.name AS course_name, c.color_code
      FROM notes n
      JOIN courses c ON n.course_id = c.id
      WHERE n.user_id = ?
    `;
    const params = [studentId];

    if (course_id) {
      sql += ` AND n.course_id = ?`;
      params.push(course_id);
    }

    sql += ` ORDER BY n.created_at DESC`;

    const notes = await db.query(sql, params);

    const parsed = notes.map(n => ({
      ...n,
      key_concepts: typeof n.key_concepts === 'string' ? JSON.parse(n.key_concepts || '[]') : (n.key_concepts || []),
      takeaways: typeof n.takeaways === 'string' ? JSON.parse(n.takeaways || '[]') : (n.takeaways || []),
      flashcards: typeof n.flashcards === 'string' ? JSON.parse(n.flashcards || '[]') : (n.flashcards || [])
    }));

    res.json(parsed);
  } catch (err) {
    console.error('Fetch notes error:', err);
    res.status(500).json({ error: 'Failed to retrieve notes.' });
  }
});

// Generate and save AI Study Notes for a topic
router.post('/generate', authenticateToken, async (req, res) => {
  try {
    const { course_id, topic, difficulty = 'medium' } = req.body;
    const userId = req.user.id;

    if (!course_id || !topic) {
      return res.status(400).json({ error: 'course_id and topic are required.' });
    }

    const course = await db.get(`SELECT id, name FROM courses WHERE id = ?`, [course_id]);
    if (!course) {
      return res.status(404).json({ error: 'Course not found.' });
    }

    // Call Anthropic Claude API (or smart pedagogical engine)
    const aiNote = await generateStudyNotes({
      topic,
      courseName: course.name,
      difficulty
    });

    const result = await db.run(
      `INSERT INTO notes (user_id, course_id, topic, summary, key_concepts, takeaways, flashcards, model_used)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        userId,
        course_id,
        aiNote.topic || topic,
        aiNote.summary || 'Summary generated by Claude Tutor.',
        JSON.stringify(aiNote.key_concepts || []),
        JSON.stringify(aiNote.takeaways || []),
        JSON.stringify(aiNote.flashcards || []),
        aiNote.model_used || 'claude-3-5-sonnet'
      ]
    );

    res.status(201).json({
      message: 'AI Study Notes generated and saved!',
      note: {
        id: result.insertId,
        course_id,
        course_name: course.name,
        ...aiNote
      }
    });
  } catch (err) {
    console.error('Notes generation error:', err);
    res.status(500).json({ error: 'Failed to generate study notes.' });
  }
});

// Delete Note
router.delete('/:id', authenticateToken, async (req, res) => {
  try {
    await db.run(`DELETE FROM notes WHERE id = ? AND user_id = ?`, [req.params.id, req.user.id]);
    res.json({ message: 'Note deleted.' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
